/**
 * Generates the canonical fixture content — `smoke/schema.ts`,
 * `smoke/SmokeFormInline.vue` and the run root's `vueform.config.ts` — from
 * the adapter's smoke config. The canonical SKELETON (the keys, the
 * required rule, the submit label, the two-item lists — everything the
 * shared specs assert) lives here, next to those specs, so an adapter
 * cannot half-edit the contract; the adapter declares only its own facts in
 * config.json: element type strings, component names, prop renames,
 * plugins. A committed file of the same name at the `tests/smoke/` root
 * wins over generation — the escape hatch for an adapter whose canonical
 * form the knobs cannot express.
 */
import fs from 'node:fs'
import path from 'node:path'

import type { AssembleFixtureInput, SmokeConfig } from './assemble'
import { exists, SmokeError } from './lib'

export interface SchemaKnob {
  /**
   * The adapter's element type string for this canonical family.
   */
  type?: string
  /**
   * The globally registered component name (inline-form families only).
   */
  component?: string
  /**
   * The adapter's name for the items/options prop (select, checkboxes).
   */
  itemsProp?: string
}

/**
 * The reference-adapter (ui) values — a config.json `schema` entry overrides
 * per family, so the reference adapter needs no knobs at all.
 */
const FAMILY_DEFAULTS: Record<string, Required<SchemaKnob>> = {
  form: { type: '', component: 'VfForm', itemsProp: '' },
  text: { type: 'text', component: 'VfText', itemsProp: '' },
  select: { type: 'select', component: 'VfSelect', itemsProp: 'items' },
  checkboxes: {
    type: 'checkboxes',
    component: 'VfCheckboxes',
    itemsProp: 'items',
  },
  group: { type: 'group', component: '', itemsProp: '' },
  list: { type: 'list', component: '', itemsProp: '' },
  grid: { type: 'grid', component: '', itemsProp: '' },
  // TODO matrix is temporarily out of the canon: its cells remount-loop
  // under vapor (register without unregister until the page hangs) — put it
  // back here, in schemaSource and in boot.spec's find loop once fixed.
  submit: { type: 'button', component: '', itemsProp: '' },
}

function resolveKnobs(
  config: SmokeConfig,
  adapter: string
): Record<string, Required<SchemaKnob>> {
  const knobs = { ...FAMILY_DEFAULTS }
  for (const [family, knob] of Object.entries(config.schema ?? {})) {
    if (!(family in FAMILY_DEFAULTS)) {
      throw new SmokeError(
        `tests/smoke/config.json of "${adapter}": unknown schema family ` +
          `"${family}" (one of: ${Object.keys(FAMILY_DEFAULTS).join(', ')}).`
      )
    }
    knobs[family] = { ...knobs[family], ...knob }
  }
  return knobs
}

const GENERATED =
  '// Generated by the smoke harness from tests/smoke/config.json. Do not'

function schemaSource(k: Record<string, Required<SchemaKnob>>): string {
  return [
    `${GENERATED}`,
    `// edit — commit tests/smoke/schema.ts to override. The KEYS, the`,
    `// required rule, the item counts and the submit label are the canonical`,
    `// contract the shared specs assert; the type strings and prop names are`,
    `// the adapter's own (config.json "schema" knobs).`,
    `import { defineSchema } from './adapter'`,
    ``,
    `export const schema = defineSchema({`,
    `  text: { type: '${k.text.type}', label: 'Text', rules: 'required' },`,
    `  select: {`,
    `    type: '${k.select.type}',`,
    `    label: 'Select',`,
    `    ${k.select.itemsProp}: { a: 'A', b: 'B' },`,
    `    default: 'a',`,
    `  },`,
    `  checkboxes: {`,
    `    type: '${k.checkboxes.type}',`,
    `    label: 'Checkboxes',`,
    `    ${k.checkboxes.itemsProp}: { x: 'X', y: 'Y' },`,
    `  },`,
    `  group: {`,
    `    type: '${k.group.type}',`,
    `    schema: { city: { type: '${k.text.type}', label: 'City' } },`,
    `  },`,
    `  list: {`,
    `    type: '${k.list.type}',`,
    `    schema: { entry: { type: '${k.text.type}', label: 'Entry' } },`,
    `  },`,
    `  grid: {`,
    `    type: '${k.grid.type}',`,
    `    cols: 2,`,
    `    grid: [['Grid', { type: '${k.text.type}', name: 'cell' }]],`,
    `  },`,
    `  submit: { type: '${k.submit.type}', action: 'submit', text: 'Submit' },`,
    `})`,
    ``,
    `export type SmokeSchema = typeof schema`,
    ``,
  ].join('\n')
}

function inlineFormSource(k: Record<string, Required<SchemaKnob>>): string {
  return [
    `<script setup lang="ts">`,
    `${GENERATED}`,
    `// edit — commit tests/smoke/SmokeFormInline.vue to override.`,
    `// The canonical form's control subset as inline GLOBAL components — no`,
    `// imports, no schema: proves the plugin's global registration and the`,
    `// GlobalComponents template typing end to end.`,
    `const items = { a: 'A', b: 'B' }`,
    `</script>`,
    ``,
    `<template>`,
    `  <${k.form.component}>`,
    `    <${k.text.component} name="text" label="Text" rules="required" />`,
    `    <${k.select.component} name="select" label="Select" :${k.select.itemsProp}="items" default="a" />`,
    `    <${k.checkboxes.component} name="checkboxes" label="Checkboxes" :${k.checkboxes.itemsProp}="items" />`,
    `  </${k.form.component}>`,
    `</template>`,
    ``,
  ].join('\n')
}

function vueformConfigSource(): string {
  return [
    `${GENERATED}`,
    `// edit — commit tests/smoke/vueform.config.ts to override. A`,
    `// representative user config: one real plugin package (always-on canon,`,
    `// its tarball injected by the harness), nothing else.`,
    `import exprEval from '@vueform/expr-eval'`,
    ``,
    `import { defineConfig } from './smoke/adapter'`,
    ``,
    `export default defineConfig({`,
    `  plugins: [exprEval()],`,
    `})`,
    ``,
  ].join('\n')
}

function setupSource(): string {
  return [
    `${GENERATED}`,
    `// edit — commit tests/smoke/setup/vite.ts to override. A no-op: this`,
    `// adapter needs no extra app wiring. An adapter built on a component`,
    `// library registers that library here (plugins, directives, theme`,
    `// css), with \`mode\` distinguishing the vdom and vapor apps.`,
    `export function setupApp(`,
    `  _app: unknown,`,
    `  _ctx: { mode: 'vdom' | 'vapor' }`,
    `) {}`,
    ``,
  ].join('\n')
}

function nuxtSetupSource(): string {
  return [
    `${GENERATED}`,
    `// edit — commit tests/smoke/setup/nuxt.ts to override. Extra Nuxt config`,
    `// the adapter's consumers need (modules, css, library options), merged`,
    `// into the generic nuxt.config.ts; adapter modules load before`,
    `// @vueform/nuxt-module.`,
    `export default {} as Record<string, unknown> & {`,
    `  modules?: string[]`,
    `  css?: string[]`,
    `}`,
    ``,
  ].join('\n')
}

/**
 * Writes the canonical files into the assembled run, each one skipped when
 * the adapter committed its own (copied there by `copyAdapterContent`).
 */
export function generateCanonicalContent(
  runDir: string,
  input: AssembleFixtureInput,
  config: SmokeConfig
) {
  const knobs = resolveKnobs(config, input.adapter)
  fs.mkdirSync(path.join(runDir, 'smoke', 'setup'), { recursive: true })

  const targets: [string, () => string][] = [
    [path.join(runDir, 'smoke', 'schema.ts'), () => schemaSource(knobs)],
    [
      path.join(runDir, 'smoke', 'SmokeFormInline.vue'),
      () => inlineFormSource(knobs),
    ],
    [path.join(runDir, 'smoke', 'setup', 'vite.ts'), () => setupSource()],
    [path.join(runDir, 'smoke', 'setup', 'nuxt.ts'), () => nuxtSetupSource()],
    [path.join(runDir, 'vueform.config.ts'), () => vueformConfigSource()],
  ]

  for (const [file, source] of targets) {
    if (!exists(file)) fs.writeFileSync(file, source())
  }
}
