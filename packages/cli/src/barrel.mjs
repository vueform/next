import { readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

/**
 * (Re)generates the CLI-owned barrel in the components directory: it imports
 * every copied Vf*.vue and exports them as one `components` map — the single
 * thing a project registers. Always rewritten in full (never hash-tracked or
 * conflict-checked), so copy runs keep it in sync with the directory. Returns
 * the barrel's filename, or null when the directory has no copies.
 */
export function writeBarrel(dirAbs, useTs) {
  const names = readdirSync(dirAbs)
    .filter((file) => /^Vf.+\.vue$/.test(file))
    .map((file) => file.slice(0, -4))
    .sort()

  if (!names.length) return null

  const filename = useTs ? 'index.ts' : 'index.js'
  const content = [
    '// Generated by `vueform copy` — do not edit; re-run copy to refresh.',
    ...names.map((name) => `import ${name} from './${name}.vue'`),
    '',
    'export const components = {',
    ...names.map((name) => `  ${name},`),
    '}',
    '',
    'export default components',
    '',
  ].join('\n')

  writeFileSync(path.join(dirAbs, filename), content)

  return filename
}
